const fs=require('fs'),vm=require('vm'),assert=require('assert');
const data=JSON.parse(fs.readFileSync('for Chrome/data/clinicalCaseBank.json','utf8'));
const appSource=fs.readFileSync('for Chrome/js/33-clinical-case-bank.js','utf8');
const local={};
let appPage='subjects';
const scroll={innerHTML:''};
const screen={querySelector:()=>scroll};
const document={baseURI:'http://localhost/',querySelector:(sel)=>sel==='#phoneContent .screen'?screen:null,addEventListener:()=>{}};
const window={};
const ctx={console,document,window,URL,localStorage:{getItem:k=>local[k]||null,setItem:(k,v)=>local[k]=v},fetch:async()=>({ok:true,json:async()=>data}),toast:()=>{},appHeader:(t)=>'<header>'+t+'</header>',appPage,appNav:()=>'<nav>Home</nav>',subjectsView:()=>'<div class="rs"><h1>Subjects</h1></div>',renderAppDemo:function(){ctx.appNav();scroll.innerHTML=ctx.appHeader('Home')+ctx.subjectsView();return scroll.innerHTML;}};
vm.createContext(ctx);
vm.runInContext(appSource,ctx,{filename:'33-clinical-case-bank.js'});
async function tick(){await new Promise(r=>setTimeout(r,0));}
(async()=>{
  assert(ctx.subjectsView().includes('Clinical Case'),'Home tile missing');
  assert(ctx.subjectsView().includes('BANK 07'),'Bank number missing');
  ctx.window.openClinicalCaseBank(); await tick(); await tick();
  assert(scroll.innerHTML.includes('Central Nervous System'),'System list not rendered');
  assert(scroll.innerHTML.includes('Cardiovascular System'),'Full system names not rendered');
  assert(scroll.innerHTML.includes('<nav>Home</nav>'),'Bottom app navigation missing on Clinical Case screen');
  ctx.window.openClinicalCaseSystem('central-nervous-system');
  assert(scroll.innerHTML.includes('Topics'),'Topic level not rendered');
  const system=data.systems[0], item=system.topics.flatMap(t=>t.cases).find(c=>c.hasSharedCaseText && c.questions.length>1), topic=system.topics.find(t=>t.cases.some(c=>c.id===item.id)), q=item.questions[0];
  ctx.window.openClinicalCaseTopic(topic.id);
  assert(scroll.innerHTML.includes('Clinical Cases'),'Case list not rendered');
  ctx.window.openClinicalCase(item.id);
  assert(scroll.innerHTML.includes('CLINICAL CASE'),'Shared clinical case narrative not rendered');
  const firstNarrativeLine=item.vignette.split('\\n')[0].trim();
  assert(scroll.innerHTML.includes(firstNarrativeLine),'Shared case text missing');
  assert((scroll.innerHTML.match(/CLINICAL CASE/g)||[]).length===1,'Shared case heading should appear once');
  assert((scroll.innerHTML.match(/class="qcard cc-question"/g)||[]).length===item.questions.length,'Questions are not grouped under the shared case');
  assert(ctx.window.__shbClinicalCaseBank.count()===1840,'Bank total does not match source');
  assert(!scroll.innerHTML.includes('Detailed Explanation'),'Detailed explanation leaked before answer');
  let wrong='A'; if(wrong===q.correctAnswer)wrong='B';
  ctx.window.answerClinicalCaseQuestion(q.id,wrong);
  const savedAnswer=JSON.parse(local['shbace_clinical_case_answers_v1'])[q.id];
  assert(savedAnswer && savedAnswer.selected===wrong,'Submitted answer was not saved');
  assert(scroll.innerHTML.includes('qopt correct'),'Correct option was not highlighted after submission');
  assert(scroll.innerHTML.includes('qopt incorrect'),'Selected wrong option was not highlighted after submission');
  ctx.window.answerClinicalCaseQuestion(q.id,q.correctAnswer);
  assert(JSON.parse(local['shbace_clinical_case_answers_v1'])[q.id].selected===wrong,'First submitted answer was not locked');
  assert(scroll.innerHTML.includes('Initial') || scroll.innerHTML.includes(q.initialExplanation.slice(0,16)),'Initial explanation did not appear after answer');
  assert(scroll.innerHTML.includes('Read More'),'Read More missing after answer');
  assert(!scroll.innerHTML.includes(q.detailedExplanation.slice(0,24)),'Detailed explanation visible before Read More');
  ctx.window.toggleClinicalCaseReadMore(q.id);
  assert(scroll.innerHTML.includes('Detailed Explanation'),'Read More did not expand');
  assert(scroll.innerHTML.includes('High-Yield Points'),'High-Yield section missing');
  assert(scroll.innerHTML.includes('Source'),'Source section missing');
  assert(local['shbace_clinical_case_answers_v1'],'Separate Clinical Case answers not persisted');
  console.log(JSON.stringify({homeTile:true,systems:true,topics:true,cases:true,initialAfterAnswer:true,readMore:true,source:true,independentStorage:true,answerLocked:true,correctAndIncorrectFeedback:true,bottomNavigation:true,testedQuestion:q.id,sharedCaseQuestions:item.questions.length,sharedCaseDisplayedOnce:true,questionCount:ctx.window.__shbClinicalCaseBank.count()},null,2));
})().catch(e=>{console.error(e);process.exit(1);});